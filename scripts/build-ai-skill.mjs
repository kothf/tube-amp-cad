#!/usr/bin/env node
/**
 * The AI features' design knowledge: compiles the circuit-design skill's reference files
 * (.claude/skills/circuit-design/references/*.md) into ai-skill.js, which the app loads.
 *
 *   node scripts/build-ai-skill.mjs          # writes ai-skill.js
 *   node scripts/build-ai-skill.mjs --check  # exits 1 when ai-skill.js is out of date
 *
 * One source for both uses: Claude Code reads the skill's files, the in-app AI gets the same
 * text in its prompts. app-format.md and schematic-style.md are for Claude Code only (the app's
 * own prompts already carry its format and its drawing is done by the CAD).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, ".claude/skills/circuit-design/references");
// section id → what circuits it is for (always: every circuit; board: layout questions)
const SECTIONS = [
  ["design-method", "always"],
  ["tube-circuits", "tube"],
  ["transistor-circuits", "semi"],
  ["analog-opamp", "opamp"],
  ["power-supplies", "always"],
  ["digital-mixed", "digital"],
  ["feedback-stability", "analog"],
  ["grounding-layout", "board"]
];
const text = Object.fromEntries(SECTIONS.map(([id]) => [id, readFileSync(join(dir, id + ".md"), "utf8").trim()]));

const out = `/* GENERATED by scripts/build-ai-skill.mjs from .claude/skills/circuit-design/references/*.md:
   edit those files and run the script, never this file (tests/ai-skill.test.mjs checks it).
   The AI features' design knowledge (the same text Claude Code reads as the circuit-design skill):
   - pack(feature, comps): the sections a feature puts in its system prompt, for the circuit on the
     sheet (comps: its parts; none: a new design, every circuit section). Empty when Settings…
     → Design knowledge in AI prompts is off.
   - kinds(comps): what kinds of circuit the parts make (tube, semi, opamp, digital). */
(function (root) {
  "use strict";
  const SECTIONS = ${JSON.stringify(text, null, 2)};
  const FOR = ${JSON.stringify(Object.fromEntries(SECTIONS))};
  // which sections each feature uses: circuit (the circuit's own kinds), board (layout and grounding)
  const FEATURES = {
    design: { circuit: true }, edit: { circuit: true }, fix: { circuit: true }, subs: { circuit: true },
    review: { circuit: true, board: true }, build: { circuit: true, board: true }, faults: { circuit: true, board: true },
    assistant: { circuit: true, board: true }, voicing: { circuit: true }
  };
  const TUBE = /^(tube|gasreg|hgrect|eye)$/, SEMI = /^(npn|pnp|nmos|pmos|njf|pjf|chipamp|reg|tl431)$/, OPAMP = /^(opamp|vcvs|vccs)$/, DIGITAL = /^(logic|logicsrc|timer555|relay|nixie)$/;
  function kinds(comps) {
    const k = new Set();
    (comps || []).forEach(c => {
      const t = c && c.type;
      if (TUBE.test(t)) k.add("tube");
      if (SEMI.test(t)) k.add("semi");
      if (OPAMP.test(t) || t === "spice" || t === "part") k.add("opamp");
      if (DIGITAL.test(t)) k.add("digital");
    });
    return k;
  }
  function enabled() { return !(root.CadSettings && root.CadSettings.get("aiKnowledge") === false); }
  function pack(feature, comps) {
    const f = FEATURES[feature]; if (!f || !enabled()) return "";
    const k = comps && comps.length ? kinds(comps) : new Set(["tube", "semi", "opamp", "digital"]);
    if (!k.size) ["tube", "semi", "opamp"].forEach(x => k.add(x));
    const analog = k.has("tube") || k.has("semi") || k.has("opamp");
    const ids = Object.keys(SECTIONS).filter(id => {
      const w = FOR[id];
      return w === "always" || (w === "board" ? f.board : w === "analog" ? analog : k.has(w));
    });
    return "\\n\\n# Design knowledge (follow it; the numbers are typical practice, the datasheet and the simulation decide)\\n\\n" + ids.map(id => SECTIONS[id]).join("\\n\\n");
  }
  root.AiSkill = { SECTIONS, FEATURES, kinds, pack, enabled };
})(typeof window !== "undefined" ? window : globalThis);
`;

const file = join(root, "ai-skill.js");
if (process.argv.includes("--check")) {
  let now = ""; try { now = readFileSync(file, "utf8"); } catch (e) { /* missing */ }
  if (now !== out) { console.error("ai-skill.js is out of date: run node scripts/build-ai-skill.mjs"); process.exit(1); }
  console.log("ai-skill.js is up to date");
} else {
  writeFileSync(file, out);
  console.log(`ai-skill.js: ${SECTIONS.length} sections, ${(out.length / 1024).toFixed(1)} kB`);
}
