#!/usr/bin/env node
/**
 * Build mpn-data.js: the case sizes of aluminium electrolytics by part number, read from the
 * makers' own datasheets (their dimension tables list every part number with its ØD × L).
 *
 *   node scripts/mpn-tables.mjs [cacheDir]
 *
 * Needs pdftotext (poppler-utils) and network access to nichicon.co.jp and
 * industrial.panasonic.com. The PDFs are kept in cacheDir (default .mpn-cache, ignored).
 * mpn.js reads the table; the app never fetches anything at run time.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cache = process.argv[2] || join(root, ".mpn-cache");
mkdirSync(cache, { recursive: true });

// Nichicon: U… radial, L… snap-in (and the screw-terminal LNR / LNX)
const NICHICON = ["UKW", "UFW", "UPW", "UHE", "UKZ", "UFG", "UKA", "UES", "UVR", "UVZ", "UCY", "UVY", "UPS", "UHW", "UBT", "UHV", "UPM", "UKL",
  "LGU", "LGN", "LGR", "LLG", "LLS", "LKG", "LKX", "LGX", "LNR", "LNX", "LGL", "LGJ"];
// Panasonic radial series: the catalogue's document ids
const PANASONIC = { FC: "ABA0000C1209", TA: "ABA0000C1212", FS: "ABA0000C1255", "ED/EE": "ABA0000C1258", FR: "ABA0000C1259" };

async function pdf(name, url) {
  const f = join(cache, name);
  if (!existsSync(f)) {
    const r = await fetch(url);
    if (!r.ok) throw new Error(`${url}: ${r.status}`);
    writeFileSync(f, Buffer.from(await r.arrayBuffer()));
  }
  return execFileSync("pdftotext", ["-layout", f, "-"], { encoding: "utf8", maxBuffer: 64 << 20, stdio: ["ignore", "pipe", "ignore"] });
}

const sizes = {};            // series -> "D×L" -> [part number suffixes]
const add = (series, pn, D, L) => {
  const s = (sizes[series] = sizes[series] || {}), k = `${+D}x${+L}`;
  (s[k] = s[k] || []);
  if (!Object.values(s).some(list => list.includes(pn.slice(series.length)))) s[k].push(pn.slice(series.length));
};

for (const s of NICHICON) {
  const text = await pdf(`nichicon-${s}.pdf`, `https://www.nichicon.co.jp/english/series_items/catalog_pdf/e-${s.toLowerCase()}.pdf`);
  let n = 0;
  for (const line of text.split("\n")) {
    // a row of the dimension table: "… 8× 11.5 … UKW1H101MPD"
    const m = new RegExp(`(\\d+(?:\\.\\d+)?)\\s*[×xX]\\s*(\\d+(?:\\.\\d+)?)\\b.*?\\b(${s}\\d[A-Z]\\d{3}[A-Z0-9]*)\\b`).exec(line);
    if (m) { add(s, m[3], m[1], m[2]); n++; }
  }
  console.log(`Nichicon ${s}: ${n}`);
}
const DIAMETERS = new Set([4, 5, 6.3, 8, 10, 12.5, 16, 18, 20, 22, 25, 30, 35, 40]);
for (const [s, id] of Object.entries(PANASONIC)) {
  const text = await pdf(`panasonic-${s.replace("/", "-")}.pdf`, `https://industrial.panasonic.com/cdbs/www-data/pdf/RDF0000/${id}.pdf`);
  let n = 0;
  for (const line of text.split("\n")) {
    // "… 8.0  11.5  555 0.117 2000 0.60 3.5 5.0 — EEUFC0J471( )": ØD and L are the first two sizes
    const m = /\b(EE[UA])([A-Z]{1,3})(\d[A-Z]\d{3}[A-Z]?)\s*(\(\s*\))?/.exec(line);
    if (!m) continue;
    const v = (line.slice(0, m.index).match(/(?<![\w.])\d+\.\d+(?![\w.])/g) || []).map(Number);
    const i = v.findIndex((x, k) => DIAMETERS.has(x) && v[k + 1] >= 5);
    if (i >= 0) { add(m[1] + m[2], m[1] + m[2] + m[3], v[i], v[i + 1]); n++; }
  }
  console.log(`Panasonic ${s}: ${n}`);
}

const body = Object.entries(sizes).map(([s, by]) => `    ${s}: {\n${Object.entries(by).filter(([, l]) => l.length).map(([k, l]) => `      "${k}": "${l.join(" ")}"`).join(",\n")}\n    }`).join(",\n");
writeFileSync(join(root, "mpn-data.js"), `/* Generated by scripts/mpn-tables.mjs from the makers' datasheets: do not edit by hand.
   Aluminium electrolytics: series -> "ØD x L" (mm) -> the part numbers of that case, without
   the series name (Nichicon e-<series>.pdf, Panasonic Industry radial lead catalogue pages). */
(function (root) {
  "use strict";
  root.MPN_CANS = {
${body}
  };
})(typeof window !== "undefined" ? window : globalThis);
`);
console.log("wrote mpn-data.js");
